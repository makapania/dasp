@pytest.mark.numerical
class TestBaselinePolynomialCorrectness:
    """Test polynomial baseline correction implementation."""

    def test_baseline_polynomial_matches_numpy(self, baseline_gold_standard: dict):
        """Verify polynomial baseline correction matches numpy.polyfit."""
        X_observed = baseline_gold_standard["X_observed"]
        X_expected = baseline_gold_standard["X_corrected"]
        degree = baseline_gold_standard["polynomial_degree"]

        # Apply Spectral Predict baseline correction
        baseline = BaselinePolynomial(degree=degree)
        X_actual = baseline.fit_transform(X_observed)

        # Compare to numpy gold standard
        np.testing.assert_allclose(
            X_actual, X_expected,
            rtol=1e-10, atol=1e-10,
            err_msg="Polynomial baseline correction does not match numpy.polyfit"
        )

    def test_baseline_polynomial_single_spectrum(self, baseline_gold_standard: dict):
        """Verify baseline correction works on single spectrum."""
        observed = baseline_gold_standard["observed_spectrum"]
        expected = baseline_gold_standard["corrected_spectrum"]
        degree = baseline_gold_standard["polynomial_degree"]

        # Reshape to 2D for transformer
        X_observed = observed.reshape(1, -1)
        X_expected = expected.reshape(1, -1)

        baseline = BaselinePolynomial(degree=degree)
        X_actual = baseline.fit_transform(X_observed)

        np.testing.assert_allclose(
            X_actual, X_expected,
            rtol=1e-10, atol=1e-10,
            err_msg="Baseline correction fails on single spectrum"
        )

    def test_baseline_polynomial_degree_1(self, derivatives_gold_standard: dict):
        """Verify linear baseline (degree=1) works correctly."""
        X_input = derivatives_gold_standard["input"]

        # Apply linear baseline
        baseline = BaselinePolynomial(degree=1)
        X_corrected = baseline.fit_transform(X_input)

        # Manually compute expected result
        wavelengths = np.arange(X_input.shape[1])
        X_expected = np.zeros_like(X_input)
        for i in range(X_input.shape[0]):
            coeffs = np.polyfit(wavelengths, X_input[i, :], deg=1)
            baseline_vals = np.polyval(coeffs, wavelengths)
            X_expected[i, :] = X_input[i, :] - baseline_vals

        np.testing.assert_allclose(
            X_corrected, X_expected,
            rtol=1e-10, atol=1e-10,
            err_msg="Linear baseline does not match numpy.polyfit"
        )

    def test_baseline_polynomial_deterministic(self, baseline_gold_standard: dict):
        """Verify baseline correction is deterministic."""
        X_observed = baseline_gold_standard["X_observed"]

        baseline = BaselinePolynomial(degree=2)
        X_result1 = baseline.fit_transform(X_observed)
        X_result2 = baseline.fit_transform(X_observed)

        np.testing.assert_array_equal(
            X_result1, X_result2,
            err_msg="Baseline correction is not deterministic"
        )

    def test_baseline_polynomial_preserves_shape(self, baseline_gold_standard: dict):
        """Verify baseline correction preserves input shape."""
        X_observed = baseline_gold_standard["X_observed"]

        baseline = BaselinePolynomial(degree=2)
        X_corrected = baseline.fit_transform(X_observed)

        assert X_corrected.shape == X_observed.shape, "Baseline correction changed array shape"


@pytest.mark.numerical
class TestPipelineCorrectness:
    """Test combined preprocessing pipelines produce correct results."""

    def test_snv_then_derivative(self, derivatives_gold_standard: dict):
        """Verify SNV followed by derivative produces correct combined result."""
        X_input = derivatives_gold_standard["input"]

        # Apply SNV then derivative
        snv = SNV()
        savgol = SavgolDerivative(deriv=1, window=7, polyorder=2)

        X_snv = snv.fit_transform(X_input)
        X_combined = savgol.fit_transform(X_snv)

        # Manually compute expected result using scipy
        from scipy.signal import savgol_filter

        # SNV
        means = X_input.mean(axis=1, keepdims=True)
        stds = X_input.std(axis=1, keepdims=True)
        stds[stds == 0] = 1.0
        X_snv_expected = (X_input - means) / stds

        # Then derivative
        X_expected = savgol_filter(X_snv_expected, window_length=7, polyorder=2, deriv=1, axis=1)

        np.testing.assert_allclose(
            X_combined, X_expected,
            rtol=1e-12, atol=1e-12,
            err_msg="SNV→Derivative pipeline does not match expected result"
        )

    def test_derivative_then_snv(self, derivatives_gold_standard: dict):
        """Verify derivative followed by SNV produces correct combined result."""
        X_input = derivatives_gold_standard["input"]

        # Apply derivative then SNV
        savgol = SavgolDerivative(deriv=1, window=7, polyorder=2)
        snv = SNV()

        X_deriv = savgol.fit_transform(X_input)
        X_combined = snv.fit_transform(X_deriv)

        # Manually compute expected result
        from scipy.signal import savgol_filter

        # Derivative
        X_deriv_expected = savgol_filter(X_input, window_length=7, polyorder=2, deriv=1, axis=1)

        # Then SNV
        means = X_deriv_expected.mean(axis=1, keepdims=True)
        stds = X_deriv_expected.std(axis=1, keepdims=True)
        stds[stds == 0] = 1.0
        X_expected = (X_deriv_expected - means) / stds

        np.testing.assert_allclose(
            X_combined, X_expected,
            rtol=1e-12, atol=1e-12,
            err_msg="Derivative→SNV pipeline does not match expected result"
        )


@pytest.mark.numerical
class TestInputValidation:
    """Test that invalid inputs are properly rejected."""

    def test_savgol_window_too_small(self, derivatives_gold_standard: dict):
        """Verify error when window < polyorder + 2."""
        X_input = derivatives_gold_standard["input"]

        # Window=5, polyorder=4 should fail (5 < 4 + 2)
        savgol = SavgolDerivative(deriv=1, window=5, polyorder=4)

        with pytest.raises(ValueError, match="Window length .* must be >= polyorder"):
            savgol.fit_transform(X_input)

    def test_savgol_window_too_large(self, derivatives_gold_standard: dict):
        """Verify auto-adjustment when window > number of features."""
        X_input = derivatives_gold_standard["input"]

        # Window larger than number of features now auto-adjusts instead of raising
        savgol = SavgolDerivative(deriv=1, window=200, polyorder=2)

        # Should auto-adjust the window and produce valid output
        result = savgol.fit_transform(X_input)
        assert result.shape == X_input.shape, "Auto-adjusted window should preserve shape"

    def test_smooth_window_too_small(self, derivatives_gold_standard: dict):
        """Verify error when smoothing window < polyorder + 2."""
        X_input = derivatives_gold_standard["input"]

        # Window=5, polyorder=4 should fail
        smooth = SavgolSmooth(window_length=5, polyorder=4)

        with pytest.raises(ValueError, match="Window length .* must be >= polyorder"):
            smooth.fit_transform(X_input)


