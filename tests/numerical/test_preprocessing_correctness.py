"""Numerical correctness tests for preprocessing transformers.

This module validates that Spectral Predict's preprocessing implementations
produce numerically identical results to validated external implementations.

All tests use gold standard reference data generated by
scripts/generate_gold_standards.py, which uses:
- SNV: Direct formula implementation
- Savitzky-Golay: scipy.signal.savgol_filter
- PLS: sklearn.cross_decomposition.PLSRegression
- Baseline: numpy.polyfit polynomial fitting

Tolerance levels:
- 1e-10: For exact mathematical operations (SNV)
- 1e-12: For scipy derivative operations
- 1e-6: For iterative algorithms (PLS, baseline)
"""

