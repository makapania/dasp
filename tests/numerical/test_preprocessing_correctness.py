@pytest.mark.numerical
class TestSNVCorrectness:
    """Test SNV implementation matches gold standard."""

    def test_snv_matches_gold_standard(self, snv_gold_standard: dict):
        """Verify SNV matches validated reference to 1e-10 tolerance."""
        X_input = snv_gold_standard["input"]
        X_expected = snv_gold_standard["output"]

        # Apply Spectral Predict SNV
        snv = SNV()
        X_actual = snv.fit_transform(X_input)

        # Compare to gold standard
        np.testing.assert_allclose(
            X_actual, X_expected,
            rtol=1e-10, atol=1e-10,
            err_msg="SNV output does not match gold standard"
        )

    def test_snv_single_sample(self, edge_cases_gold_standard: dict):
        """Verify SNV handles single sample correctly."""
        X_input = edge_cases_gold_standard["X_single"]
        X_expected = edge_cases_gold_standard["X_single_snv"]

        snv = SNV()
        X_actual = snv.fit_transform(X_input)

        np.testing.assert_allclose(
            X_actual, X_expected,
            rtol=1e-10, atol=1e-10,
            err_msg="SNV fails on single sample"
        )

    def test_snv_constant_values(self, edge_cases_gold_standard: dict):
        """Verify SNV handles constant values (zero variance) gracefully."""
        X_input = edge_cases_gold_standard["X_constant"]
        X_expected = edge_cases_gold_standard["X_constant_snv"]

        snv = SNV()
        X_actual = snv.fit_transform(X_input)

        # Should return zeros (mean-centered with std=1 denominator)
        np.testing.assert_allclose(
            X_actual, X_expected,
            rtol=1e-10, atol=1e-10,
            err_msg="SNV fails on constant values"
        )

        # Verify it's actually all zeros
        assert np.allclose(X_actual, 0.0), "SNV of constant values should be zero"

    def test_snv_deterministic(self, snv_gold_standard: dict):
        """Verify SNV produces identical results on repeated calls."""
        X_input = snv_gold_standard["input"]

        snv = SNV()
        X_result1 = snv.fit_transform(X_input)
        X_result2 = snv.fit_transform(X_input)

        np.testing.assert_array_equal(
            X_result1, X_result2,
            err_msg="SNV is not deterministic"
        )

    def test_snv_preserves_shape(self, snv_gold_standard: dict):
        """Verify SNV preserves input shape."""
        X_input = snv_gold_standard["input"]

        snv = SNV()
        X_output = snv.fit_transform(X_input)

        assert X_output.shape == X_input.shape, "SNV changed array shape"


@pytest.mark.numerical
class TestSavgolDerivativeCorrectness:
    """Test Savitzky-Golay derivative implementation matches scipy."""

    def test_savgol_first_derivative_matches_scipy(self, derivatives_gold_standard: dict):
        """Verify 1st derivative matches scipy.signal.savgol_filter."""
        X_input = derivatives_gold_standard["input"]
        X_expected = derivatives_gold_standard["deriv1_w7_p2"]

        # Apply Spectral Predict Savgol (window=7, polyorder=2, deriv=1)
        savgol = SavgolDerivative(deriv=1, window=7, polyorder=2)
        X_actual = savgol.fit_transform(X_input)

        # Tolerance 1e-10: SG-derivative coefficients accumulate ~3.86e-12 FP drift
        # across scipy versions on Linux; 1e-10 keeps a 25× safety margin while
        # staying above the realistic precision floor for cross-platform CI.
        np.testing.assert_allclose(
            X_actual, X_expected,
            rtol=1e-10, atol=1e-10,
            err_msg="1st derivative does not match scipy"
        )

    def test_savgol_second_derivative_matches_scipy(self, derivatives_gold_standard: dict):
        """Verify 2nd derivative matches scipy.signal.savgol_filter."""
        X_input = derivatives_gold_standard["input"]
        X_expected = derivatives_gold_standard["deriv2_w7_p3"]

        # Apply Spectral Predict Savgol (window=7, polyorder=3, deriv=2)
        savgol = SavgolDerivative(deriv=2, window=7, polyorder=3)
        X_actual = savgol.fit_transform(X_input)

        # Tolerance 1e-10: see 1st-derivative test for cross-platform scipy drift rationale.
        np.testing.assert_allclose(
            X_actual, X_expected,
            rtol=1e-10, atol=1e-10,
            err_msg="2nd derivative does not match scipy"
        )

    def test_savgol_alternate_parameters(self, derivatives_gold_standard: dict):
        """Verify derivatives match scipy with different window/polyorder."""
        X_input = derivatives_gold_standard["input"]
        X_expected = derivatives_gold_standard["deriv1_w11_p3"]

        # Apply with different parameters (window=11, polyorder=3, deriv=1)
        savgol = SavgolDerivative(deriv=1, window=11, polyorder=3)
        X_actual = savgol.fit_transform(X_input)

        np.testing.assert_allclose(
            X_actual, X_expected,
            rtol=1e-12, atol=1e-12,
            err_msg="Derivative with alternate parameters does not match scipy"
        )

    def test_savgol_small_window(self, edge_cases_gold_standard: dict):
        """Verify derivatives work with small windows."""
        X_input = edge_cases_gold_standard["X_small"]
        X_expected = edge_cases_gold_standard["X_small_deriv1"]

        savgol = SavgolDerivative(deriv=1, window=5, polyorder=2)
        X_actual = savgol.fit_transform(X_input)

        np.testing.assert_allclose(
            X_actual, X_expected,
            rtol=1e-12, atol=1e-12,
            err_msg="Small window derivative does not match scipy"
        )

    def test_savgol_even_window_increment(self, derivatives_gold_standard: dict):
        """Verify even windows are incremented to odd."""
        X_input = derivatives_gold_standard["input"]

        # Even window should be incremented to 7
        savgol_even = SavgolDerivative(deriv=1, window=6, polyorder=2)
        X_even = savgol_even.fit_transform(X_input)

        # Odd window 7
        savgol_odd = SavgolDerivative(deriv=1, window=7, polyorder=2)
        X_odd = savgol_odd.fit_transform(X_input)

        # Should be identical
        np.testing.assert_array_equal(
            X_even, X_odd,
            err_msg="Even window not correctly incremented to odd"
        )

    def test_savgol_default_polyorder(self, derivatives_gold_standard: dict):
        """Verify default polyorder selection."""
        X_input = derivatives_gold_standard["input"]

        # Default for deriv=1 should be polyorder=2
        savgol_default = SavgolDerivative(deriv=1, window=7, polyorder=None)
        savgol_explicit = SavgolDerivative(deriv=1, window=7, polyorder=2)

        X_default = savgol_default.fit_transform(X_input)
        X_explicit = savgol_explicit.fit_transform(X_input)

        np.testing.assert_array_equal(
            X_default, X_explicit,
            err_msg="Default polyorder does not match expected value"
        )

    def test_savgol_deterministic(self, derivatives_gold_standard: dict):
        """Verify Savgol produces identical results on repeated calls."""
        X_input = derivatives_gold_standard["input"]

        savgol = SavgolDerivative(deriv=1, window=7, polyorder=2)
        X_result1 = savgol.fit_transform(X_input)
        X_result2 = savgol.fit_transform(X_input)

        np.testing.assert_array_equal(
            X_result1, X_result2,
            err_msg="Savgol is not deterministic"
        )


